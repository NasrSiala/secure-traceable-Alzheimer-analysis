"""Generate the Q1.15 FIR coefficients (Architecture §5.6, the T2.10 recipe).

scipy.signal.remez, 111 taps, bands 0–40 Hz and 50–250 Hz, weights 1:10, fs = 500.
Quantization is rint(h × 2^15). The JSON file is the JCS document whose SHA-256
prefix is fir_coef_id; the id is not stored inside the document. Writes
saam/dsp/fir_coeffs.json and hw/rtl/fir_coeffs_pkg.vhd. Do not edit those by hand.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from scipy import signal

ROOT = Path(__file__).resolve().parents[2]
JSON_PATH = ROOT / "saam" / "dsp" / "fir_coeffs.json"
PKG_PATH = ROOT / "hw" / "rtl" / "fir_coeffs_pkg.vhd"

TAPS = 111
FS_HZ = 500
DECIMATION = 5
SUM_ABS = 62379


def quantize() -> list[int]:
    """The architecture recipe. Fails if the verified sum or the template moves."""
    response = signal.remez(
        TAPS, [0, 40, 50, FS_HZ / 2], [1, 0], weight=[1, 10], fs=FS_HZ
    )
    scaled = np.asarray(response, dtype=np.float64) * (1 << 15)
    coeffs = np.rint(scaled).astype(np.int64)
    if not np.array_equal(coeffs, coeffs[::-1]):
        raise SystemExit("remez coefficients are not symmetric")
    if int(np.abs(coeffs).sum()) != SUM_ABS:
        raise SystemExit(f"sum |q| = {int(np.abs(coeffs).sum())}, expected {SUM_ABS}")
    if int(np.max(np.abs(coeffs))) > 32767:
        raise SystemExit("a coefficient does not fit in Q1.15")
    _check_template(coeffs)
    return [int(value) for value in coeffs]


def _check_template(coeffs: np.ndarray) -> None:
    frequencies, response = signal.freqz(coeffs / (1 << 15), worN=8192, fs=FS_HZ)
    magnitude = np.abs(response)
    passband = magnitude[frequencies <= 40]
    stopband = magnitude[frequencies >= 50]
    ripple = 20.0 * np.log10(float(passband.max() / passband.min()))
    attenuation = -20.0 * np.log10(float(stopband.max()))
    # Documented on 2026-10-06 after quantization: 0.379 dB and 52.6 dB.
    if not 0.37 < ripple < 0.39:
        raise SystemExit(f"passband ripple {ripple:.4f} dB is not the verified design")
    if not 52.0 < attenuation < 53.5:
        raise SystemExit(
            f"stopband attenuation {attenuation:.4f} dB is not the verified design"
        )


def jcs_bytes(coeffs: list[int]) -> bytes:
    """RFC 8785 for this document: sorted keys, no spaces, integers only."""
    document = {
        "decimation": DECIMATION,
        "fs_hz": FS_HZ,
        "q": coeffs,
        "taps": TAPS,
    }
    return json.dumps(
        document, ensure_ascii=True, separators=(",", ":"), sort_keys=True
    ).encode("ascii")


def coef_id(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()[:8]


def package_text(coeffs: list[int], identifier: str) -> str:
    rows: list[str] = []
    for start in range(0, TAPS, 8):
        row = ", ".join(str(value) for value in coeffs[start : start + 8])
        comma = "," if start + 8 < TAPS else ""
        rows.append(f"    {row}{comma}")
    body = "\n".join(rows)
    return (
        "-- Generated by hw/gen/gen_fir_coeffs.py. Do not edit.\n"
        "-- scipy.signal.remez(111, [0, 40, 50, 250], [1, 0], weight=[1, 10], fs=500)\n"
        "-- Quantization: rint(h * 2^15). fir_coef_id is the first 8 hex digits of\n"
        "-- SHA-256(saam/dsp/fir_coeffs.json), the JCS bytes with no trailing newline.\n"
        "\n"
        "library ieee;\n"
        "use ieee.std_logic_1164.all;\n"
        "\n"
        "package fir_coeffs_pkg is\n"
        f"  constant TAP_COUNT : natural := {TAPS};\n"
        f"  constant DECIMATION : natural := {DECIMATION};\n"
        f'  constant COEF_ID : std_logic_vector(31 downto 0) := x"{identifier}";\n'
        f"  type coef_array_t is array (0 to {TAPS - 1}) of integer;\n"
        "  constant COEFS : coef_array_t := (\n"
        f"{body}\n"
        "  );\n"
        "end package fir_coeffs_pkg;\n"
    )


def main() -> None:
    coeffs = quantize()
    payload = jcs_bytes(coeffs)
    identifier = coef_id(payload)
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_bytes(payload)
    PKG_PATH.write_bytes(package_text(coeffs, identifier).encode("ascii"))
    print(f"fir_coef_id={identifier} sum_abs={SUM_ABS} taps={TAPS}")


if __name__ == "__main__":
    main()
